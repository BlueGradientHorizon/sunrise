const NATIVE: &str =
    "\n[native]\ngame = '26.3'\nsunrise = '0123456789abcdef0123456789abcdef01234567'\n";
const CARGO: &str = "[package]\nname = 'example-crate'\nversion  = \"1.4.2\" # crate version\n";
const LOCK: &str = "\
# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = \"example-crate\"
version = \"1.4.2\"
dependencies = [\"dependency\"]

[[package]]
name = \"dependency\"
version = \"2.0.0\"
source = \"registry+https://github.com/rust-lang/crates.io-index\"
checksum = \"543210\"
";

fn registry(url: &str) -> Result<Option<String>, String> {
    Ok(Some(match url {
        "https://raw.githubusercontent.com/sunrise-org/sunrise-mods/main/registry/watched.toml" => {
            WATCHED.into()
        }
        "https://raw.githubusercontent.com/sunrise-org/sunrise-mods/main/registry/release-workflow.toml" =>
        {
            format!("uses = '{USES}'")
        }
        _ => panic!("unexpected URL: {url}"),
    }))
}

#[test]
fn registration_uses_name_then_repository_id_and_exact_package_path() {
    for remote in [
        "https://github.com/Author/example.git",
        "ssh://git@github.com/author/example.git",
        "git@github.com:author/example.git",
    ] {
        registered(&registry, remote, "mods/example").unwrap();
        assert_eq!(
            registered(&registry, remote, "mods").unwrap_err(),
            NOT_REGISTERED
        );
    }
    assert_eq!(
        registered(&registry, "https://github.com.example/author/example", ".").unwrap_err(),
        NOT_REGISTERED
    );
    let api_calls = std::cell::Cell::new(0);
    let fetch = |url: &str| {
        if url == "https://api.github.com/repos/author/renamed" {
            api_calls.set(api_calls.get() + 1);
            Ok(Some(r#"{"id":101,"full_name":"author/renamed"}"#.into()))
        } else {
            registry(url)
        }
    };
    registered(&fetch, "git@github.com:author/renamed.git", ".").unwrap();
    assert_eq!(api_calls.get(), 1);
    let fetch = |url: &str| {
        if url == "https://api.github.com/repos/author/unregistered" {
            Ok(Some(r#"{"id":102}"#.into()))
        } else {
            registry(url)
        }
    };
    assert_eq!(
        registered(&fetch, "git@github.com:author/unregistered.git", ".").unwrap_err(),
        NOT_REGISTERED
    );
    let unknown = format!("unknown = true\n{WATCHED}");
    assert!(
        registered(
            &|_| Ok(Some(unknown.clone())),
            "git@github.com:author/example.git",
            "."
        )
        .unwrap_err()
        .contains("unknown field")
    );
}

#[test]
fn caller_matches_root_and_subfolder_workflow_contract() {
    assert_eq!(caller("", ".", USES), TEMPLATE);
    assert_eq!(
        caller("example/", "mods/example", USES),
        TEMPLATE
            .replace("['v*']", "['example/v*']")
            .replace("path: .", "path: mods/example")
    );
    assert!(caller("example/", "mods/a: b", USES).ends_with("path: \"mods/a: b\"\n"));
    assert!(caller("example/", ".nan", USES).ends_with("path: \".nan\"\n"));
}

#[test]
fn bumps_use_semver_precedence() {
    let old = Version::parse("1.4.2+build").unwrap();
    for (request, want) in [
        ("patch", "1.4.3"),
        ("minor", "1.5.0"),
        ("major", "2.0.0"),
        ("1.5.0-alpha", "1.5.0-alpha"),
    ] {
        assert_eq!(next_version(&old, request).unwrap().to_string(), want);
    }
    for request in ["1.4.2+new", "1.4.1", "1.4", "bananas"] {
        assert!(next_version(&old, request).is_err());
    }
}

