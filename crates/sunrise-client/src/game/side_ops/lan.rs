//! Role-dispatched LAN side operations (rewritten to `SideOps` traits at switch).
use crate::game::Game;
use sunrise_sim::lan::guest::Guest;

impl<__Side: crate::game::Side> Game<'_, __Side> {
    /// Whether a server player rides `vehicle` (`Entity.isPassenger`: a
    /// passenger does not use a portal on its own, the vehicle carries it
    /// across, `Entity.teleportCrossDimension`).
    pub(in crate::game) fn guest_rides(&self, vehicle: u32) -> bool {
        <__Side as SideOps>::side_guest_rides(&self.side, vehicle)
    }

    #[inline(always)]
    pub(in crate::game) fn side_object_target(
        &self,
        id: i32,
    ) -> Option<([f64; 3], [f64; 3], [f64; 3])> {
        <__Side as SideOps>::side_object_target(self, id)
    }
}

// Generated by Shape G codemod from side_* role dispatchers.
pub(in crate::game) trait SideOps: Sized {
    fn side_guest_rides(&self, vehicle: u32) -> bool;
    fn side_command_players(&self) -> impl Iterator<Item = &Guest>;

    fn side_object_target(
        game: &crate::game::Game<'_, Self>,
        id: i32,
    ) -> Option<([f64; 3], [f64; 3], [f64; 3])>;
}
#[allow(unused_variables)]
impl SideOps for crate::game::server_side::ServerState {
    fn side_guest_rides(&self, vehicle: u32) -> bool {
        self.lan
            .as_ref()
            .is_some_and(|h| h.hub.guests.iter().any(|g| g.vehicle == Some(vehicle)))
    }
    fn side_command_players(&self) -> impl Iterator<Item = &Guest> {
        self.lan.iter().flat_map(|h| h.hub.online_players())
    }

    fn side_object_target(
        game: &crate::game::Game<'_, Self>,
        id: i32,
    ) -> Option<([f64; 3], [f64; 3], [f64; 3])> {
        game.server_object_target(id)
    }
}
#[cfg(feature = "client")]
#[allow(unused_variables)]
impl SideOps for crate::game::client_side::ClientState {
    fn side_guest_rides(&self, vehicle: u32) -> bool {
        false
    }
    fn side_command_players(&self) -> impl Iterator<Item = &Guest> {
        std::iter::empty()
    }

    fn side_object_target(
        game: &crate::game::Game<'_, Self>,
        id: i32,
    ) -> Option<([f64; 3], [f64; 3], [f64; 3])> {
        game.client_object_target(id)
    }
}
