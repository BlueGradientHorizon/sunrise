//! Role-dispatched UI, chat, block-entity NBT, item-splash, and level-bound side operations.
use crate::game::Game;
use sunrise_client::entities::ItemSplash;
use sunrise_core::nbt::Tag;

impl<__Side: crate::game::Side> Game<'_, __Side> {
    #[inline(always)]
    pub(in crate::game) fn side_block_entity_nbt(&self, pos: [i32; 3]) -> Option<Tag> {
        <__Side as SideOps>::side_block_entity_nbt(self, pos)
    }

    #[inline(always)]
    pub(in crate::game) fn side_send_chat_command(&mut self, command: &str) {
        <__Side as SideOps>::side_send_chat_command(self, command)
    }

    #[inline(always)]
    pub(in crate::game) fn side_apply_item_splash(&mut self, splash: ItemSplash) {
        <__Side as SideOps>::side_apply_item_splash(self, splash)
    }

    #[inline(always)]
    pub(in crate::game) fn side_level_min_y(&self) -> i32 {
        <__Side as SideOps>::side_level_min_y(self)
    }
}

// Generated by Shape G codemod from side_* role dispatchers.
pub(in crate::game) trait SideOps: Sized {
    fn side_block_entity_nbt(game: &crate::game::Game<'_, Self>, pos: [i32; 3]) -> Option<Tag>;
    fn side_send_chat_command(game: &mut crate::game::Game<'_, Self>, command: &str);
    fn side_apply_item_splash(game: &mut crate::game::Game<'_, Self>, splash: ItemSplash);
    fn side_level_min_y(game: &crate::game::Game<'_, Self>) -> i32;
}
#[allow(unused_variables)]
