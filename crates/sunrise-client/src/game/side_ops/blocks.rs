//! Role dispatchers owned by lane `blocks` (`side_ops/blocks.rs`).
use crate::game::{Game, piston_push, stations_common};
use sunrise_client::{Result, containers::BlockEntity};
use sunrise_client_render::moving_colliders::Prepared;
use sunrise_core::{geometry::Vec3, nbt::Tag};
use sunrise_world::entity_move::MoverType;

impl<__Side: crate::game::Side> Game<'_, __Side> {
    pub(in crate::game) fn side_encode_live_block_entity(
        &self,
        key: (i32, i32, i32),
        entity: &BlockEntity,
        block: &str,
    ) -> Tag {
        <__Side as SideOps>::side_encode_live_block_entity(self, key, entity, block)
    }

    pub(in crate::game) fn side_station_changed(&mut self) {
        <__Side as SideOps>::side_station_changed(self)
    }

    pub(in crate::game) fn side_combiner_take_effects(
        &mut self,
        kind: stations_common::Kind,
        pos: [i32; 3],
        level_change: i32,
    ) -> bool {
        <__Side as SideOps>::side_combiner_take_effects(self, kind, pos, level_change)
    }

    pub(in crate::game) fn side_move_local_player(
        &mut self,
        mover: MoverType,
        movement: Vec3,
        auto_jump: bool,
    ) -> Result<Option<Vec3>> {
        <__Side as SideOps>::side_move_local_player(self, mover, movement, auto_jump)
    }

    pub(in crate::game) fn side_push_piston_entities(&mut self, pushes: Vec<piston_push::Push>) {
        <__Side as SideOps>::side_push_piston_entities(self, pushes)
    }

    pub(in crate::game) fn side_carry_pass(&mut self, start: &Prepared) {
        <__Side as SideOps>::side_carry_pass(self, start)
    }
}

// Generated by Shape G codemod from side_* role dispatchers.
pub(in crate::game) trait SideOps: Sized {
    fn side_encode_live_block_entity(
        game: &crate::game::Game<'_, Self>,
        key: (i32, i32, i32),
        entity: &BlockEntity,
        block: &str,
    ) -> Tag;
    fn side_station_changed(game: &mut crate::game::Game<'_, Self>);
    fn side_combiner_take_effects(
        game: &mut crate::game::Game<'_, Self>,
        kind: stations_common::Kind,
        pos: [i32; 3],
        level_change: i32,
    ) -> bool;
    fn side_move_local_player(
        game: &mut crate::game::Game<'_, Self>,
        mover: MoverType,
        movement: Vec3,
        auto_jump: bool,
    ) -> Result<Option<Vec3>>;
    fn side_push_piston_entities(
        game: &mut crate::game::Game<'_, Self>,
        pushes: Vec<piston_push::Push>,
    );
    fn side_carry_pass(game: &mut crate::game::Game<'_, Self>, start: &Prepared);
}
